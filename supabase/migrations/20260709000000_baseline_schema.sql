-- Baseline schema: the tables that existed before migrations were tracked.
--
-- The first version of the project was built in the Supabase dashboard, so
-- these six tables (and match_documents, used by n8n's vector-store node) had
-- no migration. This file recreates them exactly as they were, so that
-- `supabase db reset` builds the whole database from an empty project.
--
-- It intentionally includes the original loose policies and anon grants:
-- the next migration (20260709120000_multitenant_rls.sql) replaces them with
-- per-tenant row-level security.

create extension if not exists vector with schema public;

-- ---------------------------------------------------------------------------
-- tables
-- ---------------------------------------------------------------------------

create table if not exists public.clients (
  id         uuid primary key default gen_random_uuid(),
  email      text not null unique,
  auto_send  boolean not null default false,
  created_at timestamptz default now()
);

create table if not exists public.documents (
  id           bigserial primary key,
  content      text,
  metadata     jsonb,
  embedding    public.vector(1536),
  client_email text
);

create table if not exists public.email_logs (
  id               bigserial primary key,
  sender_email     text,
  subject          text,
  incoming_message text,
  ai_response      text,
  label            text,
  created_at       timestamptz default timezone('utc', now()),
  thread_id        text,
  client_email     text,
  message_id       text,
  status           text default 'pending_review',
  final_response   text
);

create table if not exists public.ai_recommendations (
  email       text primary key,
  suggestions text not null
);

create table if not exists public.login_logs (
  user_id    uuid not null,
  email      text primary key,
  user_agent text,
  event_type text not null default 'login',
  created_at timestamptz not null default now()
);

create table if not exists public.policy_requests (
  id              bigint generated by default as identity primary key,
  user_email      text not null,
  request_details text not null,
  status          text not null default 'Pending'
                  check (status in ('Pending', 'In Progress', 'Completed')),
  created_at      timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- knowledge-base similarity search (called by n8n's Supabase Vector Store node)
-- ---------------------------------------------------------------------------

create or replace function public.match_documents(
  query_embedding public.vector,
  match_count     integer default null,
  filter          jsonb default '{}'
)
returns table (id bigint, content text, metadata jsonb, embedding public.vector, similarity double precision)
language plpgsql
as $$
#variable_conflict use_column
begin
  return query
  select
    id,
    content,
    metadata,
    embedding,
    1 - (documents.embedding <=> query_embedding) as similarity
  from public.documents
  where metadata @> filter
  order by documents.embedding <=> query_embedding
  limit match_count;
end;
$$;

-- ---------------------------------------------------------------------------
-- original access rules (replaced by the next migration)
-- ---------------------------------------------------------------------------

alter table public.clients         enable row level security;
alter table public.email_logs      enable row level security;
alter table public.policy_requests enable row level security;

create policy "Allow anon insert on ai_recommendations" on public.ai_recommendations for insert to anon with check (true);
create policy "Users can view own recommendations"      on public.ai_recommendations for select using (auth.email() = email);
create policy "Enable insert for all users"             on public.email_logs for insert with check (true);
create policy "Enable read access for all users"        on public.email_logs for select using (true);
create policy "anon can insert login_logs"              on public.login_logs for insert to anon with check (true);
create policy "anon insert"                             on public.policy_requests for insert with check (true);
create policy "anon read"                               on public.policy_requests for select using (true);
create policy "anon update"                             on public.policy_requests for update using (true) with check (true);

grant all on table public.clients, public.documents, public.email_logs,
                   public.ai_recommendations, public.login_logs, public.policy_requests
  to anon, authenticated, service_role;
grant all on all sequences in schema public to anon, authenticated, service_role;
grant all on function public.match_documents(public.vector, integer, jsonb) to anon, authenticated, service_role;
